def demirbas_denetle(metin):
    doc = nlp(metin)

    # 1. Kural: Gereksiz Sözcük Kullanımı (Örnek: "Geri iade etmek")
    # "İade" zaten geri yapılan bir şeydir.
    gereksiz_sozcukler = [("geri", "iade")]

    # 2. Kural: Çelişen Sözcüklerin Kullanımı (Örnek: "Tam yaklaşıktır")
    celisen_sozcukler = [("tam", "yaklaşık"), ("eminim", "belki")]

    sonuc = {
        "metin": metin,
        "hatalar": [],
        "analiz": []
    }

    # Kelime Analizlerini Topla
    kelimeler = [t.text.lower() for t in doc]

    # Kural Kontrolü: Gereksiz Sözcük
    for ikili in gereksiz_sozcukler:
        if ikili[0] in kelimeler and ikili[1] in kelimeler:
            sonuc["hatalar"].append(f"⚠️ Gereksiz sözcük kullanımı: '{ikili[1]}' zaten '{ikili[0]}' anlamını taşır.")

    # Kural Kontrolü: Çelişen Sözcük
    for ikili in celisen_sozcukler:
        if ikili[0] in kelimeler and ikili[1] in kelimeler:
            sonuc["hatalar"].append(f"⚠️ Çelişen sözcüklerin kullanımı: '{ikili[0]}' kesinlik, '{ikili[1]}' ihtimal bildirir.")

    return sonuc

